def generate_user_profiles(num_users: int = 150, seed: int = 42) -> List[Dict[str, Any]]:
    """Creates a diverse pool of synthetic user profiles with normal spending baselines."""
    rng = random.Random(seed)
    np_rng = np.random.default_rng(seed)
    profiles = []

    for i in range(1, num_users + 1):
        user_id = f"USR_{i:04d}"
        home_loc = rng.choice(LOCATIONS)
        primary_dev = rng.choice(DEVICES)
        default_pay = rng.choice(PAYMENT_METHODS)

        # Diverse user spending demographics (students, professionals, high-net-worth)
        user_tier = rng.choices(["budget", "regular", "affluent"], weights=[0.4, 0.45, 0.15])[0]
        if user_tier == "budget":
            avg_amount = float(np_rng.uniform(15.0, 55.0))
            std_amount = float(avg_amount * np_rng.uniform(0.2, 0.35))
        elif user_tier == "regular":
            avg_amount = float(np_rng.uniform(60.0, 220.0))
            std_amount = float(avg_amount * np_rng.uniform(0.25, 0.45))
        else:  # affluent
            avg_amount = float(np_rng.uniform(300.0, 850.0))
            std_amount = float(avg_amount * np_rng.uniform(0.3, 0.6))

        profiles.append(
            {
                "user_id": user_id,
                "home_location": home_loc,
                "primary_device": primary_dev,
                "default_payment_method": default_pay,
                "avg_amount": round(avg_amount, 2),
                "std_amount": round(std_amount, 2),
                "created_at": datetime.now(timezone.utc).isoformat(),
            }
        )
    return profiles


class SyntheticTransactionGenerator:
    """
    Stateful generator for continuous or batch synthetic transaction streams.
    Tracks user recent state in memory for continuous velocity simulation.
    """

    def __init__(self, user_profiles: Optional[List[Dict[str, Any]]] = None, seed: int = 42):
        self.rng = random.Random(seed)
        self.np_rng = np.random.default_rng(seed)
        self.user_profiles = user_profiles or generate_user_profiles(150, seed=seed)
        self.user_lookup = {u["user_id"]: u for u in self.user_profiles}

        # Keep rolling user state for continuous realistic simulation
        self.user_state: Dict[str, Dict[str, Any]] = {}
        for u in self.user_profiles:
            self.user_state[u["user_id"]] = {
                "last_tx_time": datetime.now(timezone.utc) - timedelta(hours=self.rng.randint(2, 48)),
                "last_location": u["home_location"],
                "last_device": u["primary_device"],
                "tx_history_1h": [],
            }

    def generate_single_transaction(
        self,
        user_id: Optional[str] = None,
        force_fraud: Optional[bool] = None,
        fraud_scenario: Optional[str] = None,
        timestamp: Optional[datetime] = None,
    ) -> Dict[str, Any]:
        """
        Generates a realistic transaction with ground-truth simulation labels.
        Labels are kept strictly separate from inference features.
        """
        if not user_id:
            user_id = self.rng.choice(list(self.user_lookup.keys()))

        profile = self.user_lookup[user_id]
        state = self.user_state[user_id]
        now = timestamp or datetime.now(timezone.utc)

        # Decide fraud status
        is_fraud = (
            force_fraud
            if force_fraud is not None
            else (self.rng.random() < 0.05)
        )

        scenario = "none"
        risk_indicators = []

        if not is_fraud:
            # Normal spending with occasional legitimate splurge or travel
            is_splurge = self.rng.random() < 0.05
            multiplier = self.rng.uniform(2.0, 3.8) if is_splurge else 1.0
            amount = max(
                3.50,
                self.np_rng.normal(profile["avg_amount"] * multiplier, profile["std_amount"]),
            )
            # Normal merchant categories
            cat = self.rng.choices(
                ["Grocery", "Dining & Quick Bites", "Fuel & Transport", "Electronics", "Travel & Lodging", "Digital & Gaming"],
                weights=[0.40, 0.25, 0.15, 0.10, 0.06, 0.04],
            )[0]
            merchant = self.rng.choice(MERCHANTS_BY_CATEGORY[cat])
            # Occasional legitimate domestic/business travel (6% of normal transactions)
            is_traveling = self.rng.random() < 0.06
            location = self.rng.choice(LOCATIONS) if is_traveling else profile["home_location"]
            device = (
                profile["primary_device"]
                if self.rng.random() < 0.88
                else self.rng.choice(DEVICES)
            )
            payment_method = (
                profile["default_payment_method"]
                if self.rng.random() < 0.84
                else self.rng.choice(PAYMENT_METHODS)
            )
            channel = "In-Store" if cat in ("Grocery", "Fuel & Transport") and self.rng.random() < 0.6 else "Online"

        else:
            # FRAUD TRANSACTION — pick scenario
            selected_scenario = fraud_scenario or self.rng.choice([
                "high_amount_outlier",
                "rapid_velocity_burst",
                "impossible_geo_travel",
                "suspicious_new_device",
                "off_hours_crypto",
            ])
            scenario = selected_scenario

            if selected_scenario == "high_amount_outlier":
                multiplier = self.rng.uniform(6.5, 22.0)
                amount = profile["avg_amount"] * multiplier + self.rng.uniform(250.0, 1500.0)
                cat = self.rng.choice(["Luxury & Jewelry", "Electronics", "Digital & Gaming"])
                merchant = self.rng.choice(MERCHANTS_BY_CATEGORY[cat])
                location = profile["home_location"]
                device = profile["primary_device"]
                payment_method = "Credit Card"
                channel = "Online"
                risk_indicators.append(f"Spending spike ({multiplier:.1f}x user baseline)")

            elif selected_scenario == "rapid_velocity_burst":
                amount = profile["avg_amount"] * self.rng.uniform(1.5, 4.0)
                cat = "Digital & Gaming"
                merchant = self.rng.choice(MERCHANTS_BY_CATEGORY[cat])
                location = profile["home_location"]
                device = self.rng.choice(FRAUD_DEVICES)
                payment_method = profile["default_payment_method"]
                channel = "Online"
                risk_indicators.append("Rapid transaction velocity burst detected")

            elif selected_scenario == "impossible_geo_travel":
                amount = profile["avg_amount"] * self.rng.uniform(1.8, 5.5)
                cat = self.rng.choice(["Travel & Lodging", "Luxury & Jewelry", "Electronics"])
                merchant = self.rng.choice(MERCHANTS_BY_CATEGORY[cat])
                location = self.rng.choice(FRAUD_LOCATIONS)
                device = self.rng.choice(FRAUD_DEVICES)
                payment_method = "Credit Card"
                channel = "Online"
                risk_indicators.append(f"Impossible geo travel anomaly to {location}")

            elif selected_scenario == "suspicious_new_device":
                amount = profile["avg_amount"] * self.rng.uniform(2.5, 8.0)
                cat = self.rng.choice(["Electronics", "Digital & Gaming"])
                merchant = self.rng.choice(MERCHANTS_BY_CATEGORY[cat])
                location = profile["home_location"]
                device = self.rng.choice(FRAUD_DEVICES)
                payment_method = self.rng.choice(["Credit Card", "Digital Wallet"])
                channel = "Online"
                risk_indicators.append(f"Suspicious proxy device: {device}")

            else:  # off_hours_crypto
                amount = profile["avg_amount"] * self.rng.uniform(3.0, 10.0)
                cat = "Digital & Gaming"
                merchant = "Crypto Exchange Portal"
                location = self.rng.choice(FRAUD_LOCATIONS)
                device = self.rng.choice(FRAUD_DEVICES)
                payment_method = "Credit Card"
                channel = "Online"
                risk_indicators.append("Late night high-risk crypto portal transaction")

        tx_id = f"TXN_{uuid.uuid4().hex[:12].upper()}"

        # Clean history older than 1 hour in state cache
        one_hour_ago = now - timedelta(hours=1)
        state["tx_history_1h"] = [
            t for t in state["tx_history_1h"] if t["time"] >= one_hour_ago
        ]

        tx_record = {
            "transaction_id": tx_id,
            "user_id": user_id,
            "amount": round(float(amount), 2),
            "timestamp": now.isoformat(),
            "merchant": merchant,
            "merchant_category": cat,
            "location": location,
            "device": device,
            "payment_method": payment_method,
            "channel": channel,
            "ground_truth_label": 1 if is_fraud else 0,
            "fraud_scenario": scenario,
            "simulation_notes": risk_indicators,
            "data_source": "SIMULATED_DATA_PIPELINE",
        }

        # Update user rolling state
        state["tx_history_1h"].append({"time": now, "amount": float(amount)})
        state["last_tx_time"] = now
        state["last_location"] = location
        state["last_device"] = device

        return tx_record

    def generate_batch(
        self,
        count: int = 10000,
        fraud_rate: float = 0.045,
        start_date: Optional[datetime] = None,
    ) -> pd.DataFrame:
        """
        Generates a structured synthetic dataset for training and offline evaluation.
        Maintains realistic temporal dispersion across past 30 days.
        """
        records = []
        end_time = datetime.now(timezone.utc)
        start_time = start_date or (end_time - timedelta(days=21))
        total_seconds = int((end_time - start_time).total_seconds())

        print(f"[Generator] Generating {count} synthetic transactions (fraud_rate={fraud_rate:.1%})...")

        for idx in range(count):
            user_id = self.rng.choice(list(self.user_lookup.keys()))
            rand_sec = self.rng.randint(0, total_seconds)
            tx_time = start_time + timedelta(seconds=rand_sec)
            is_fraud = self.rng.random() < fraud_rate

            tx = self.generate_single_transaction(
                user_id=user_id,
                force_fraud=is_fraud,
                timestamp=tx_time,
            )
            records.append(tx)

        df = pd.DataFrame(records)
        df["timestamp"] = pd.to_datetime(df["timestamp"])
        df = df.sort_values("timestamp").reset_index(drop=True)
        # Convert timestamp back to ISO format string
        df["timestamp"] = df["timestamp"].dt.strftime("%Y-%m-%dT%H:%M:%S%z")
        # Handle timezone formatting if needed
        df["timestamp"] = df["timestamp"].apply(
            lambda x: x if "+" in x or "Z" in x else x + "+00:00"
        )
        return df


def generate_training_data(
    n_samples: int = 25000,
    fraud_rate: float = 0.045,
    seed: int = 42,
) -> Tuple[pd.DataFrame, List[Dict[str, Any]]]:
    """Generates synthetic dataset and user profiles for training pipeline."""
    profiles = generate_user_profiles(num_users=200, seed=seed)
    gen = SyntheticTransactionGenerator(user_profiles=profiles, seed=seed)
    df = gen.generate_batch(count=n_samples, fraud_rate=fraud_rate)
    return df, profiles


